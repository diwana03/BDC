const fs=require('fs');
const source=fs.readFileSync('admin/dance-cup/participants.php','utf8');
const version=JSON.parse(fs.readFileSync('VERSION.json','utf8'));
const assert=(ok,message)=>{if(!ok)throw new Error(message)};
assert(source.includes('bdc_profile_request_dance_cup_categories'),'registration category source missing');
assert(source.includes('Dance Participation')&&source.includes('Linked Profiles')&&source.includes('Profiles To Set Up'),'participant and profile datasets are not separated');
assert(source.includes('One row for each participant and category'),'category explanation missing');
assert(source.includes('registration_status')&&source.includes("<>'rejected'"),'category registration status missing');
const releaseNumber=Number(version.version.match(/^2\.3\.3-dev(\d+)$/)?.[1]||0);
assert(releaseNumber>=449&&version.build>=3155,'release must retain dev449 registration-category support');
console.log('Dance Cup registration categories dashboard v449 checks passed.');
