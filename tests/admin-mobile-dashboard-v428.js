'use strict';
const fs=require('fs');
const assert=require('assert');
const read=p=>fs.readFileSync(p,'utf8');
const css=read('public/assets/css/admin-mobile-v428.css');
const js=read('public/assets/js/admin-mobile-v428.js');
const dashboard=read('app/Views/admin/dashboard.php');
const competitors=read('admin/competitors/index.php');
const judges=read('admin/judges/index.php');
const scoring=read('public/css/scoring-premium.css');
assert(css.includes('@media(max-width:850px)')&&css.includes('translateX(-105%)'),'dashboard navigation must become an off-canvas mobile drawer');
assert(css.includes('min-height:44px')&&css.includes('overflow-x:auto'),'mobile controls must be touch sized and wide tables safely scroll');
assert(css.includes('table[data-mobile-cards] td:before'),'management tables must expose mobile field labels');
assert(js.includes("aria-expanded")&&js.includes("event.key==='Escape'")&&js.includes('enhanceTables'),'mobile navigation and table enhancement must be accessible');
assert(dashboard.includes('admin-mobile-v428.css')&&dashboard.includes('admin-mobile-v428.js'),'main dashboard must load the mobile layer');
assert(competitors.includes('data-mobile-cards')&&competitors.includes('bdc-mobile-actions'),'competitor records and toolbar must be mobile responsive');
assert(judges.includes('data-mobile-cards')&&judges.includes('scoring-premium.css?v=428'),'judge directory must use shared mobile styling');
assert(scoring.includes('admin-mobile-v428.css?v=428'),'Dance Cup and scoring screens must inherit the mobile layer');
console.log('admin mobile dashboard v428 regression passed');
